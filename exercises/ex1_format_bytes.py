def format_bytes(n):
        for unit in ("B", "KB", "MB", "GB", "TB"): #先看看这个字节单位都有什么
          if n<1024: #因为是 1024 才会进一个单位，所以如果它小于 1024，那它就是在当前单位区间。
            return f"{n:.0f} {unit}" if unit=="B" else f"{n:.1f} {unit}" #如果是最小单位的话，那就返回整数；如果不是最小单位的话，那就保留一位小数。
          n/=1024 #如果它大于0.24，那就除以1024
        return f"{n:.1f} PB" #PB作为超大数据兜底
        
